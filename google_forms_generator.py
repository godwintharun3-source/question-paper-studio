import json
import re

def clean_stem_and_ta(q_en_raw, q_ta_raw):
    q_en_raw = str(q_en_raw or '').strip()
    q_ta_raw = str(q_ta_raw or '').strip()

    if '|' in q_en_raw:
        parts = q_en_raw.split('|', 1)
        q_en_raw = parts[0].strip()
        if not q_ta_raw or q_ta_raw == q_en_raw:
            q_ta_raw = parts[1].strip()
    elif '|' in q_ta_raw:
        parts = q_ta_raw.split('|', 1)
        if not q_en_raw:
            q_en_raw = parts[0].strip()
        q_ta_raw = parts[1].strip()

    q_en_clean = re.sub(r'^\s*(?:Q(?:uestion)?\s*[\.\:\-]?)?\s*\d+[\.\)\:\-\s]+', '', q_en_raw, flags=re.I).strip()
    q_ta_clean = re.sub(r'^\s*(?:Q(?:uestion)?\s*[\.\:\-]?)?\s*\d+[\.\)\:\-\s]+', '', q_ta_raw, flags=re.I).strip()

    if not q_en_clean and q_ta_clean:
        q_en_clean = q_ta_clean
        q_ta_clean = ''

    return q_en_clean, q_ta_clean

def generate_google_apps_script(paper_data):
    """
    Generates a Google Apps Script that automatically creates a self-grading
    Google Forms Quiz in the user's Google Drive.
    """
    header = paper_data.get('header', {})
    title = header.get('test_title', 'ITI Trade Question Paper')
    inst_name = header.get('inst_name', 'Industrial Training Institute')
    marks_text = header.get('marks_text', '20')
    description = f"{inst_name}\\n{header.get('date_text', '')} | {marks_text}".strip()

    questions = paper_data.get('questions', [])
    if not questions and 'pages' in paper_data:
        # Flatten from pages
        questions = [q for p in paper_data['pages'] for q in p]

    # Calculate points per question
    marks_digits = re.findall(r'\d+', marks_text)
    total_marks = int(marks_digits[0]) if marks_digits else len(questions)
    points_per_q = max(1, round(total_marks / max(1, len(questions))))

    js_lines = []
    js_lines.append("// ==========================================================")
    js_lines.append("// Auto-Generated Google Apps Script to create Google Form")
    js_lines.append("// Generated by Question Paper Studio")
    js_lines.append("// ==========================================================")
    js_lines.append("")
    js_lines.append("function createGoogleFormQuiz() {")
    js_lines.append(f'  var form = FormApp.create({json.dumps(title)});')
    js_lines.append(f'  form.setDescription({json.dumps(description)});')
    js_lines.append('  form.setIsQuiz(true);')
    js_lines.append('  form.setAllowResponseEdits(false);')
    js_lines.append('  form.setShowLinkToRespondAgain(false);')
    js_lines.append('  form.setConfirmationMessage("Your exam answers have been submitted successfully!");')
    js_lines.append('')
    
    # Collect Student Details first
    js_lines.append('  // Student Information Section')
    js_lines.append('  var nameItem = form.addTextItem();')
    js_lines.append('  nameItem.setTitle("Trainee Name / மாணவர் பெயர்").setRequired(true);')
    js_lines.append('  var rollItem = form.addTextItem();')
    js_lines.append('  rollItem.setTitle("Roll No / Reg No / பதிவு எண்").setRequired(true);')
    js_lines.append('')

    current_section = None
    curr_q_num = 1

    for q in questions:
        q_en, q_ta = clean_stem_and_ta(q.get('q_en', ''), q.get('q_ta', ''))

        # Check section/subheading
        subheading = q.get('subheading') or q.get('module')
        if subheading and subheading != current_section and subheading != "General":
            current_section = subheading
            js_lines.append(f'  // Section: {current_section}')
            js_lines.append('  var sec = form.addSectionHeaderItem();')
            js_lines.append(f'  sec.setTitle({json.dumps(f"Section: {current_section}")});')
            js_lines.append('')

        # Question Title (Bilingual)
        if q_ta and q_ta.lower() != q_en.lower():
            q_title = f"{curr_q_num}. {q_en}\n{q_ta}"
        else:
            q_title = f"{curr_q_num}. {q_en}"

        options = q.get('options', [])
        valid_opts = [o for o in options if o.get('en') or o.get('ta')]

        if valid_opts:
            # Multiple Choice Question
            ans_letter = str(q.get('ans', 'A')).strip().upper()
            js_lines.append(f'  // Question {curr_q_num} (MCQ)')
            js_lines.append('  var mcqItem = form.addMultipleChoiceItem();')
            js_lines.append(f'  mcqItem.setTitle({json.dumps(q_title)});')
            js_lines.append(f'  mcqItem.setPoints({points_per_q});')
            
            choices_code = []
            for o in valid_opts:
                opt_letter = o.get('opt', '').upper()
                o_en = re.sub(r'^\s*[A-D][\.\)\:\-\s]+', '', o.get('en', '')).strip()
                o_ta = re.sub(r'^\s*[A-D][\.\)\:\-\s]+', '', o.get('ta', '')).strip()
                if o_ta and o_ta.lower() != o_en.lower():
                    choice_label = f"({opt_letter}) {o_en} / {o_ta}"
                else:
                    choice_label = f"({opt_letter}) {o_en}"
                
                is_correct = "true" if opt_letter == ans_letter else "false"
                choices_code.append(f'mcqItem.createChoice({json.dumps(choice_label)}, {is_correct})')
                
            js_lines.append(f'  mcqItem.setChoices([{", ".join(choices_code)}]);')
            js_lines.append('  mcqItem.setRequired(true);')
        else:
            # Short Answer Question (No Options)
            js_lines.append(f'  // Question {curr_q_num} (Short Answer)')
            js_lines.append('  var txtItem = form.addTextItem();')
            js_lines.append(f'  txtItem.setTitle({json.dumps(q_title)});')
            js_lines.append(f'  txtItem.setPoints({points_per_q});')
            js_lines.append('  txtItem.setRequired(true);')

        js_lines.append('')
        curr_q_num += 1

    js_lines.append('  // Form Summary Logs')
    js_lines.append('  Logger.log("=== Google Form Created Successfully! ===");')
    js_lines.append('  Logger.log("Form Edit URL: " + form.getEditUrl());')
    js_lines.append('  Logger.log("Form Public View URL: " + form.getPublishedUrl());')
    js_lines.append('  return { editUrl: form.getEditUrl(), publishedUrl: form.getPublishedUrl() };')
    js_lines.append('}')

    return "\n".join(js_lines)

def generate_manual_form_text(paper_data):
    """
    Generates plain-text quiz format for manual pasting or Form Builder extensions.
    """
    header = paper_data.get('header', {})
    title = header.get('test_title', 'ITI Trade Question Paper')
    inst_name = header.get('inst_name', 'Industrial Training Institute')
    marks_text = header.get('marks_text', '20')

    questions = paper_data.get('questions', [])
    if not questions and 'pages' in paper_data:
        questions = [q for p in paper_data['pages'] for q in p]

    lines = []
    lines.append(f"Title: {title}")
    lines.append(f"Institution: {inst_name}")
    lines.append(f"Marks: {marks_text}")
    lines.append("=" * 50)
    lines.append("")

    curr_q_num = 1
    current_subheading = None

    for q in questions:
        subheading = q.get('subheading') or q.get('module')
        if subheading and subheading != current_subheading and subheading != "General":
            current_subheading = subheading
            lines.append(f"--- [ SECTION: {current_subheading} ] ---")
            lines.append("")

        q_en, q_ta = clean_stem_and_ta(q.get('q_en', ''), q.get('q_ta', ''))

        lines.append(f"{curr_q_num}. {q_en}")
        if q_ta and q_ta.lower() != q_en.lower():
            lines.append(f"   {q_ta}")

        options = q.get('options', [])
        valid_opts = [o for o in options if o.get('en') or o.get('ta')]
        ans_letter = str(q.get('ans', 'A')).strip().upper()

        if valid_opts:
            for o in valid_opts:
                opt_letter = o.get('opt', '').upper()
                o_en = re.sub(r'^\s*[A-D][\.\)\:\-\s]+', '', o.get('en', '')).strip()
                o_ta = re.sub(r'^\s*[A-D][\.\)\:\-\s]+', '', o.get('ta', '')).strip()
                ta_str = f" / {o_ta}" if o_ta and o_ta.lower() != o_en.lower() else ""
                mark = "*" if opt_letter == ans_letter else ""
                lines.append(f"   {mark}({opt_letter}) {o_en}{ta_str}")
        else:
            lines.append("   [Short Answer / Descriptive Question]")

        lines.append("")
        curr_q_num += 1

    return "\n".join(lines)
